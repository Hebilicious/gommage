function asObject(value: unknown): Record<string, unknown> {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return {};
  }

  return value as Record<string, unknown>;
}

function asBoolean(value: unknown, fallback: boolean): boolean {
  return typeof value === "boolean" ? value : fallback;
}

function asNullableNumber(value: unknown, fallback: number | null): number | null {
  if (value === null) {
    return null;
  }

  return typeof value === "number" && Number.isFinite(value) ? value : fallback;
}

function asStringArray(value: unknown, fallback: string[]): string[] {
  if (!Array.isArray(value)) {
    return [...fallback];
  }

  return value.filter((entry): entry is string => typeof entry === "string");
}

/**
 * Accepts a single revision string or a list of them, dropping empty entries so
 * a blank config value falls back to the caller's default.
 */
function asRevisionSelector(value: unknown): RevisionSelector | undefined {
  if (typeof value === "string") {
    return value.length > 0 ? value : undefined;
  }

  if (!Array.isArray(value)) {
    return undefined;
  }

  const ranges = value.filter(
    (entry): entry is string => typeof entry === "string" && entry.length > 0,
  );

  return ranges.length > 0 ? ranges : undefined;
}

/** Normalizes any revision selector into the argument list git receives. */
export function normalizeRanges(value: RevisionSelector | undefined | null): string[] {
  if (value === undefined || value === null) {
    return [];
  }

  const entries = Array.isArray(value) ? value : [value];

  return entries.map((entry) => entry.trim()).filter(Boolean);
}

function normalizeGpgSign(value: boolean | string | undefined): true | string | null {
  if (value === undefined || value === false) {
    return null;
  }

  if (value === true) {
    return true;
  }

  const keyId = value.trim();
  return keyId.length > 0 ? keyId : true;
}

function buildCommitFilter(signing: true | string): string {
  const keyArgument = signing === true ? "-S" : `-S${quoteForShell(signing)}`;
  return `git commit-tree ${keyArgument} "$@"`;
}

function assertUsableReplacementIdentity(identity: CommitIdentity, config: GommageConfig): void {
  if (
    !isAiIdentity(identity) &&
    !matchesBlockedDomain(identity.email, config.rules.blockedDomains)
  ) {
    return;
  }

  throw new Error(
    `Refusing to rewrite history: the replacement identity "${identity.name} <${identity.email}>" is itself an AI identity or a blocked domain, so commits would not actually be cleaned up. Set git user.name/user.email to the human identity, or pass --author-name and --author-email.`,
  );
}
